function input_args = pure_snow_inputs(config)
% 显式列出冻结 SNICAR-ADv3 接口的 34 个字段。
% 单层纯净球形雪；dz 为 m，rho_snw 为 kg/m^3，rds_snw 为 um。
% 零浓度组分仍需提供字段，由 SNICAR 决定读取哪些光学属性。
input_args = struct( ...
    'direct_beam', 1, ...
    'coszen', 0.5, ...
    'dz', config.forward.depth_m, ...
    'rho_snw', config.forward.density_kg_m3, ...
    'rds_snw', 100, ...
    'ice_ri', config.forward.ice_ri, ...
    'sno_shp', config.forward.snow_shape, ...
    'sno_fs', 0, ...
    'sno_ar', 0, ...
    'dust_type', 1, ...
    'ash_type', 1, ...
    'mss_cnc_sot1', 0, ...
    'mss_cnc_sot2', 0, ...
    'mss_cnc_brc1', 0, ...
    'mss_cnc_brc2', 0, ...
    'mss_cnc_dst1', 0, ...
    'mss_cnc_dst2', 0, ...
    'mss_cnc_dst3', 0, ...
    'mss_cnc_dst4', 0, ...
    'mss_cnc_dst5', 0, ...
    'mss_cnc_ash1', 0, ...
    'mss_cnc_ash2', 0, ...
    'mss_cnc_ash3', 0, ...
    'mss_cnc_ash4', 0, ...
    'mss_cnc_ash5', 0, ...
    'cell_nbr_conc', 0, ...
    'alg_rds', 10, ...
    'dcmf_pig_chla', 0.015, ...
    'dcmf_pig_chlb', 0.005, ...
    'dcmf_pig_cara', 0.05, ...
    'dcmf_pig_carb', 0, ...
    'R_sfc_all_wvl', config.forward.substrate_albedo, ...
    'atm', config.forward.atmosphere, ...
    'flx_dwn_bb', 1.0);
assert(numel(fieldnames(input_args)) == 34, 'Unexpected SNICAR input interface');
end
